export function getCountryName(cuisineName) {
  const name = String(cuisineName || "").trim();

  return cuisineToCountry[name] || name;
}

export function getCountrySlug(cuisineName) {
  return getCountryName(cuisineName)
    .toLowerCase()
    .trim()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}
